export const NARRATIVE_TIMING = Object.freeze({
  character: 34,
  comma: 105,
  sentence: 220,
  lineBreak: 260,
  paragraph: 330,
  chapter: 820,
  opening: 360,
  finalHold: 1800
});

function characterDelay(character) {
  if (character === "\n") return NARRATIVE_TIMING.lineBreak;
  if (/[。！？!?]/.test(character)) return NARRATIVE_TIMING.sentence;
  if (/[，、；：,;:]/.test(character)) return NARRATIVE_TIMING.comma;
  return NARRATIVE_TIMING.character;
}

export function createNarrativeTimeline(stopId) {
  const chapters=JOURNEY_NARRATIVES[stopId];
  if(!chapters)return null;
  const segments=[],revealTimes=[];
  let elapsed=NARRATIVE_TIMING.opening,offset=0;
  chapters.forEach((chapter,chapterIndex)=>{
    if(chapterIndex)elapsed+=NARRATIVE_TIMING.chapter;
    const entries=[{kind:"title",text:chapter.title,chapter:chapterIndex},...chapter.paragraphs.map(paragraph=>({kind:"paragraph",chapter:chapterIndex,...paragraph}))];
    entries.forEach((entry,entryIndex)=>{
      if(entryIndex)elapsed+=NARRATIVE_TIMING.paragraph;
      const start=offset;
      for(const character of entry.text){elapsed+=characterDelay(character);revealTimes.push(elapsed);offset++;}
      segments.push({...entry,start,end:offset});
    });
  });
  const typingDuration=revealTimes.at(-1)??0;
  return {stopId,segments,revealTimes,totalCharacters:offset,typingDuration,duration:typingDuration+NARRATIVE_TIMING.finalHold};
}

export function visibleCharactersAt(timeline,elapsed) {
  if(!timeline||elapsed<0)return 0;
  let low=0,high=timeline.revealTimes.length;
  while(low<high){const middle=(low+high)>>1;if(timeline.revealTimes[middle]<=elapsed)low=middle+1;else high=middle;}
  return low;
}

export function narrativePlainText(stopId) {
  return (JOURNEY_NARRATIVES[stopId]??[]).map(chapter=>[chapter.title,...chapter.paragraphs.map(p=>p.text)].join("\n\n")).join("\n\n");
}
